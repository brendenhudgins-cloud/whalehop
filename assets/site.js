/* =========================================================== HERO + COPY */

function renderHero(C) {
  $("#hero-tag").textContent = C.game.tagline;

  const cta = $("#cta");
  const s = C.cta.steam || {};
  const url = safeURL(s.url || "");
  cta.append(
    url
      ? el("a", { class: "btn", text: s.label, ...ext(url) })
      : el("span", { class: "btn soon", text: s.soonLabel || s.label, "aria-disabled": "true" })
  );
  if (C.cta.secondary?.href) {
    cta.append(el("a", { class: "btn ghost", text: C.cta.secondary.label, href: C.cta.secondary.href }));
  }
  if (!url && s.note) $("#cta-note").textContent = s.note;

  $("#blurb").textContent = C.game.blurb;
  const pitch = $("#pitch");
  for (const line of C.game.pitch || []) pitch.append(el("li", { text: line }));

  const facts = $("#facts");
  for (const f of C.facts || []) {
    facts.append(el("div", { class: "fact" }, [
      el("b", { text: f.n }),
      el("span", { text: f.label }),
      f.sub ? el("em", { text: f.sub }) : null,
    ]));
  }
}

function renderFeatures(C) {
  const g = $("#features-grid");
  for (const f of C.features || []) {
    g.append(el("article", { class: "panel feat rise", "data-accent": f.accent || "teal" }, [
      el("p", { class: "eyebrow", text: f.eyebrow }),
      el("h3", { text: f.title }),
      el("p", { text: f.body }),
    ]));
  }
}

function renderShots(C) {
  const g = $("#shots");
  for (const s of C.shots || []) {
    g.append(el("figure", { class: "shot rise" }, [
      el("img", {
        src: `img/${s.file}`, alt: `${s.band} — ${s.caption}`,
        loading: "lazy", decoding: "async", width: 1600, height: 900,
      }),
      el("figcaption", {}, [
        el("span", { class: "band", text: s.band }),
        el("p", { class: "cap", text: s.caption }),
      ]),
    ]));
  }
}

/* =========================================================== FEEDS */

function itemBluesky(p) {
  const href = safeURL(p.url);
  if (!href) return null;
  const kids = [
    el("span", { class: "when", text: ago(p.date) }),
    el("p", { class: "txt", text: p.text || "(no text)" }),
  ];
  if (p.images?.length) {
    const strip = el("div", { class: "thumbs" });
    for (const im of p.images.slice(0, 4)) {
      const t = safeURL(im.thumb);
      if (t) strip.append(el("img", { src: t, alt: im.alt || "", loading: "lazy", decoding: "async" }));
    }
    if (strip.children.length) kids.push(strip);
  }
  const meta = [];
  if (p.likes) meta.push(el("span", {}, [el("b", { text: num(p.likes) }), document.createTextNode(" ♥")]));
  if (p.reposts) meta.push(el("span", {}, [el("b", { text: num(p.reposts) }), document.createTextNode(" ⇌")]));
  if (p.replies) meta.push(el("span", {}, [el("b", { text: num(p.replies) }), document.createTextNode(" ✎")]));
  if (meta.length) kids.push(el("div", { class: "meta" }, meta));
  return el("a", { class: "item", ...ext(href) }, kids);
}

function itemYouTube(v) {
  const href = safeURL(v.url);
  if (!href) return null;
  const cover = safeURL(v.thumb);
  const meta = [el("span", { text: ago(v.date) })];
  if (v.views != null) meta.push(el("span", {}, [el("b", { text: num(v.views) }), document.createTextNode(" views")]));
  return el("a", { class: "item row", ...ext(href) }, [
    cover ? el("img", { class: "cover", src: cover, alt: "", loading: "lazy", decoding: "async" }) : null,
    el("div", { class: "body" }, [
      el("p", { class: "txt", text: v.title }),
      el("div", { class: "meta" }, meta),
    ]),
  ]);
}

function itemMusic(t) {
  const href = safeURL(t.url);
  if (!href) return null;
  const cover = safeURL(t.cover);
  const meta = [];
  if (t.duration) meta.push(el("span", { text: t.duration }));
  if (t.tags?.length) meta.push(el("span", { text: t.tags.join(" · ") }));
  if (!meta.length) meta.push(el("span", { text: ago(t.date) }));
  return el("a", { class: "item row sq", ...ext(href) }, [
    cover ? el("img", { class: "cover", src: cover, alt: "", loading: "lazy", decoding: "async" }) : null,
    el("div", { class: "body" }, [
      el("p", { class: "txt", text: t.title }),
      el("div", { class: "meta" }, meta),
    ]),
  ]);
}

/* A release, pinned above the loose tracks. `feeds.json` carried these from the first
   version and nothing drew them — data a page fetches and never shows is data nobody
   notices has gone wrong, which is how the track URLs stayed broken. Either render it or
   stop fetching it; this renders it. */
function itemAlbum(a) {
  const href = safeURL(a.url);
  if (!href) return null;
  const cover = safeURL(a.cover);
  const meta = [el("span", { class: "tag", text: "ALBUM" })];
  if (a.tracks) meta.push(el("span", { text: `${a.tracks} tracks` }));
  if (a.year) meta.push(el("span", { text: a.year }));
  return el("a", { class: "item row sq album", ...ext(href) }, [
    cover ? el("img", { class: "cover", src: cover, alt: "", loading: "lazy", decoding: "async" }) : null,
    el("div", { class: "body" }, [
      el("p", { class: "txt", text: a.title }),
      el("div", { class: "meta" }, meta),
    ]),
  ]);
}

const RENDERERS = { bluesky: itemBluesky, youtube: itemYouTube, music: itemMusic };

function feedPanel(key, cfg, src) {
  const make = RENDERERS[key];
  const list = el("div", { class: "feed-list", id: `list-${key}` });

  const items = [
    ...(src?.albums || []).map(itemAlbum),
    ...(src?.items || []).map(make),
  ].filter(Boolean);
  if (items.length) list.append(...items);
  else {
    // A source that failed keeps its last good answer server-side, so an empty
    // panel means there was never anything to show — say which, rather than
    // leaving a blank box that reads as a broken layout.
    list.append(el("div", { class: "empty" }, [
      el("b", { text: src?.error ? "could not reach" : "nothing yet" }),
      document.createTextNode(src?.error ? `${cfg.label} did not answer. Showing nothing rather than something stale.`
                                         : `No posts cached yet. Run tools/site-feeds.mjs.`),
    ]));
  }

  const at = src?.fetched ? `updated ${ago(src.fetched)}` : "";
  const href = safeURL(cfg.url) || "#";

  return el("section", { class: "feed rise", "data-src": key, id: `feed-${key}` }, [
    el("div", { class: "feed-head" }, [
      el("span", { class: "dot" }),
      el("h3", { text: cfg.label }),
      el("span", { class: "at", text: at, title: src?.fetched || "" }),
    ]),
    el("p", { class: "feed-blurb", text: cfg.blurb || "" }),
    list,
    el("p", { class: "feed-foot" }, [
      el("a", { class: "feed-more", ...ext(href), text: `${cfg.handle || cfg.label} — see everything` }),
    ]),
  ]);
}

function renderFeeds(C, F) {
  const grid = $("#feeds-grid");
  const order = ["bluesky", "youtube", "music", "twitch"];
  let shown = 0;
  for (const key of order) {
    const cfg = C.social?.[key];
    if (!cfg || cfg.enabled === false) continue;
    if (!RENDERERS[key]) continue;   // configured but nothing knows how to draw it
    grid.append(feedPanel(key, cfg, F.sources?.[key]));
    shown++;
  }
  $("#feeds-sub").textContent = F.generated
    ? `Three feeds, pulled straight from the source. Last refreshed ${ago(F.generated)}.`
    : `Three feeds, pulled straight from the source.`;

  const links = $("#foot-links");
  for (const key of order) {
    const cfg = C.social?.[key];
    const href = cfg && cfg.enabled !== false && safeURL(cfg.url);
    if (href) links.append(el("a", { ...ext(href), text: cfg.label }));
  }
  return shown;
}

/* ---- the one source a browser is allowed to refresh for itself ---- */
async function refreshBluesky(C) {
  const cfg = C.social?.bluesky;
  if (!cfg || cfg.enabled === false || !cfg.live || !cfg.handle) return;
  const limit = Math.min(50, (C.feedLimits?.bluesky || 6) * 3);
  const base = "https://public.api.bsky.app/xrpc";

  let feed;
  try {
    const r = await fetch(
      `${base}/app.bsky.feed.getAuthorFeed?actor=${encodeURIComponent(cfg.handle)}` +
      `&limit=${limit}&filter=posts_no_replies`
    );
    if (!r.ok) throw new Error(`HTTP ${r.status}`);
    feed = await r.json();
  } catch {
    return;   // keep the cached list — see "the cache is the floor" above
  }

  const want = C.feedLimits?.bluesky || 6;
  const items = [];
  for (const row of feed.feed || []) {
    if (row.reason) continue;              // a repost carries someone else's name
    const p = row.post;
    if (!p?.record) continue;
    const emb = p.embed || {};
    items.push({
      url: `https://bsky.app/profile/${cfg.handle}/post/${String(p.uri).split("/").pop()}`,
      text: (p.record.text || "").replace(/\s+/g, " ").trim(),
      date: p.record.createdAt || p.indexedAt,
      likes: p.likeCount || 0, reposts: p.repostCount || 0, replies: p.replyCount || 0,
      images: (emb.images || emb.media?.images || []).slice(0, 4)
        .map((i) => ({ thumb: i.thumb, alt: i.alt || "" })),
    });
    if (items.length >= want) break;
  }
  if (!items.length) return;

  const list = $("#list-bluesky");
  if (!list) return;
  list.replaceChildren(...items.map(itemBluesky).filter(Boolean));
  const at = $("#feed-bluesky .at");
  if (at) { at.textContent = "updated just now"; at.title = new Date().toISOString(); }
}

/* =========================================================== THE RAIL
   Each <section> declares the band it stands in. The rail is built from those,
   and the active entry follows whichever section owns the middle of the viewport
   — not whichever is merely intersecting, which flickers between two neighbours
   for the whole overlap. */
function buildRail() {
  const secs = $$("main .sec").concat([$(".hero")]).filter(Boolean);
  const stops = $$("main .sec").map((s) => ({
    id: s.id, band: s.dataset.band, alt: Number(s.dataset.alt || 0), node: s,
  }));
  const list = $(".rail-list");
  const links = stops.map((s) => {
    const a = el("a", { href: `#${s.id}` }, [
      el("span", { text: s.band }),
    ]);
    a.append(el("span", { class: "rail-alt", text: `${num(s.alt)}m` }));
    list.append(el("li", {}, [a]));
    return a;
  });

  const dot = $(".rail-dot");
  const railH = () => $(".rail-line").clientHeight;

  let ticking = false;
  const sync = () => {
    ticking = false;
    const mid = window.scrollY + innerHeight / 2;
    let idx = -1;
    stops.forEach((s, i) => { if (s.node.offsetTop <= mid) idx = i; });
    links.forEach((a, i) => a.classList.toggle("on", i === idx));

    const doc = document.documentElement.scrollHeight - innerHeight;
    const p = doc > 0 ? Math.min(1, Math.max(0, window.scrollY / doc)) : 0;
    if (dot) dot.style.top = `${p * railH()}px`;
  };
  addEventListener("scroll", () => {
    if (!ticking) { ticking = true; requestAnimationFrame(sync); }
  }, { passive: true });
  addEventListener("resize", sync, { passive: true });
  sync();
  void secs;
}

function reveal() {
  const targets = $$(".rise");
  if (!("IntersectionObserver" in window)) { targets.forEach((t) => t.classList.add("in")); return; }
  const io = new IntersectionObserver((rows) => {
    for (const r of rows) if (r.isIntersecting) { r.target.classList.add("in"); io.unobserve(r.target); }
  }, { rootMargin: "0px 0px -8% 0px", threshold: 0.06 });
  targets.forEach((t) => io.observe(t));
}

/* =========================================================== BOOT */

(async () => {
  // `no-store` on content.json only: it is small, it is the thing being edited, and a
  // cached copy is exactly what makes an edit look like it did not take. feeds.json is
  // rewritten by the deploy, so it may be cached normally.
  const [C, F] = await Promise.all([
    fetch("content.json", { cache: "no-store" }).then((r) => r.json()),
    fetch("feeds.json").then((r) => r.json()).catch(() => ({ sources: {} })),
  ]);

  document.title = C.site?.title || document.title;

  renderSections(C);
  renderHero(C);
  renderFeatures(C);
  renderShots(C);
  renderFeeds(C, F);

  $("#foot-line").textContent = C.footer?.line || "";
  $("#foot-col").textContent = C.footer?.colophon || "";

  buildRail();
  reveal();

  refreshBluesky(C);   // fire and forget: the page is already complete without it
})().catch((e) => {
  console.error("[whale-hop site]", e);
  const w = $("#what .wrap");
  if (w) w.prepend(el("p", { class: "empty", text: `Could not load content.json — ${e.message}` }));
});
