/* WHALE HOP — promo site renderer.
   ---------------------------------------------------------------------------
   Reads two files and builds the page from them:

     content.json   hand-written. Copy, links, which shots appear, how many feed
                    items each panel shows. Edit this to change the site.
     feeds.json     generated by tools/site-feeds.mjs. Never hand-edited.

   Nothing below hardcodes a handle, a URL or a line of copy — if a string shows
   up on the page and is not in content.json, that is a bug in this file.

   ONE SOURCE REFRESHES LIVE, AND ONLY ONE. Measured with
   `curl -I -H "Origin: https://example.com"`: Bluesky's public AppView sends
   `Access-Control-Allow-Origin: *`, YouTube's RSS and Rauversion send no CORS
   header at all. So Bluesky is re-fetched in the browser on top of the cache and
   the other two are served from it. A source is marked `live:true` in
   content.json to opt in; if one of the other two ever gains CORS, flipping that
   flag is the whole change.

   THE CACHE IS THE FLOOR, NOT THE CEILING. The cached list renders first and the
   live fetch replaces it only on success. A rate-limited or offline visitor sees
   the last good posts, never an empty panel — which is the same rule
   tools/site-feeds.mjs follows on the server side, for the same reason.
   --------------------------------------------------------------------------- */

const $ = (s, r = document) => r.querySelector(s);
const $$ = (s, r = document) => [...r.querySelectorAll(s)];

/* Build DOM rather than assembling HTML strings: every value below comes from a
   third-party feed, and `textContent` cannot be talked into executing anything.
   The one exception is the SVG favicon in the head, which is static. */
function el(tag, props = {}, kids = []) {
  const n = document.createElement(tag);
  for (const [k, v] of Object.entries(props)) {
    if (v == null || v === false) continue;
    if (k === "class") n.className = v;
    else if (k === "text") n.textContent = v;
    else if (k.startsWith("data-")) n.setAttribute(k, v);
    else n[k] = v;
  }
  for (const c of [].concat(kids)) if (c) n.append(c);
  return n;
}

const num = (n) => (n == null ? "" : Number(n).toLocaleString("en-US"));

/* "3 days ago" up to a month, then an absolute date. A feed panel is about
   recency, and "2026-06-19" answers a different question than "2 months ago". */
function ago(iso) {
  if (!iso) return "";
  const t = new Date(iso);
  if (isNaN(t)) return "";
  const s = (Date.now() - t.getTime()) / 1000;
  if (s < 60) return "just now";
  if (s < 3600) return `${Math.floor(s / 60)}m ago`;
  if (s < 86400) return `${Math.floor(s / 3600)}h ago`;
  if (s < 86400 * 30) return `${Math.floor(s / 86400)}d ago`;
  return t.toLocaleDateString("en-US", { year: "numeric", month: "short", day: "numeric" });
}

/* Only ever emit links we constructed or that arrived over https. A feed item is
   third-party text; `javascript:` in an href is the obvious way that bites. */
function safeURL(u) {
  // Guard the blank case FIRST: new URL("", location.href) succeeds and hands back the
  // current page, so `safeURL(cta.steam.url || "")` on a null url produced a live-looking
  // button that linked to the site itself.
  if (typeof u !== "string" || !u.trim()) return null;
  try {
    const p = new URL(u, location.href);
    return p.protocol === "https:" || p.protocol === "http:" ? p.href : null;
  } catch { return null; }
}

const ext = (href) => ({ href, target: "_blank", rel: "noopener noreferrer" });

/* =========================================================== SECTIONS

   The section eyebrows, headings and subheads used to be literals in index.html,
   which quietly broke the rule at the top of this file — a string on the page and
   not in content.json. They are ids now, and `content.sections` fills them, so
   "edit content.json, commit, done" is true of every word again. `setText` is a
   no-op when either the node or the string is missing, so index.html keeps its
   own text as the fallback and a missing key is never a blank heading. */

function setText(sel, value) {
  const n = $(sel);
  if (n && typeof value === "string" && value.trim()) n.textContent = value;
}

